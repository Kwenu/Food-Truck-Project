-- Role of the signed-in user ('admin' | 'manager' | 'kitchen'), or NULL for customers.
create or replace function public.staff_role()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select role from public.staff_profiles where user_id = auth.uid() and active
$$;

-- What a customer is allowed to see of an order: no phone number, first name only.
create or replace function public.order_public_json(o public.orders)
returns jsonb
language sql
stable
as $$
  select to_jsonb(o) || jsonb_build_object(
    'customer_phone', '',
    'customer_name', split_part(btrim(o.customer_name), ' ', 1)
  )
$$;

