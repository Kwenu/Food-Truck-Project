-- Orders: staff may change status / payment only; history + payment side effects are server-side.
create or replace function public.orders_before_update()
returns trigger
language plpgsql
as $$
begin
  if new.id is distinct from old.id
     or new.number is distinct from old.number
     or new.type is distinct from old.type
     or new.table_number is distinct from old.table_number
     or new.customer_name is distinct from old.customer_name
     or new.customer_phone is distinct from old.customer_phone
     or new.lines is distinct from old.lines
     or new.totals is distinct from old.totals
     or new.created_at is distinct from old.created_at then
    raise exception 'Order details cannot be changed after placing.';
  end if;

  if public.staff_role() = 'kitchen'
     and (new.payment_status is distinct from old.payment_status
          or new.payment_method is distinct from old.payment_method
          or new.payment_reference is distinct from old.payment_reference) then
    raise exception 'Kitchen accounts cannot change payment details.';
  end if;

  -- The kitchen only cooks: approved → preparing → ready (or reject). Approving new orders and
  -- marking them served/collected is done by managers/admins.
  if public.staff_role() = 'kitchen' and new.status is distinct from old.status then
    if not ((old.status = 'confirmed' and new.status in ('preparing', 'rejected'))
         or (old.status = 'preparing' and new.status in ('ready', 'rejected'))) then
      raise exception 'Kitchen accounts can only start preparing or mark orders ready.';
    end if;
  end if;

  if new.status is distinct from old.status then
    new.history := old.history || jsonb_build_array(jsonb_build_object('status', new.status, 'at', now()));
    if new.status = 'completed' and new.payment_status = 'pending' then
      new.payment_status := 'paid';
    end if;
    if new.status = 'rejected' and new.payment_status = 'paid' then
      new.payment_status := 'refunded';
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists orders_before_update on public.orders;
create trigger orders_before_update
  before update on public.orders
  for each row execute function public.orders_before_update();

-- Never allow the restaurant to end up with no active admin.
create or replace function public.keep_one_admin()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (select 1 from public.staff_profiles where role = 'admin' and active) then
    raise exception 'At least one active admin is required.';
  end if;
  return null;
end;
$$;

drop trigger if exists staff_keep_one_admin on public.staff_profiles;
create trigger staff_keep_one_admin
  after update or delete on public.staff_profiles
  for each row execute function public.keep_one_admin();

