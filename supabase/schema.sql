  using (active or public.staff_role() is not null);
create policy "promotions insert" on public.promotions for insert
  with check (coalesce(public.staff_role(), '') in ('admin', 'manager'));
create policy "promotions update" on public.promotions for update
  using (coalesce(public.staff_role(), '') in ('admin', 'manager'))
  with check (coalesce(public.staff_role(), '') in ('admin', 'manager'));
create policy "promotions delete" on public.promotions for delete
  using (coalesce(public.staff_role(), '') in ('admin', 'manager'));

-- orders: ONLY signed-in staff can read or update. Customers have no direct access at all
-- (they create orders through place_order() and read their own through get_orders()).
drop policy if exists "orders staff read"   on public.orders;
drop policy if exists "orders staff update" on public.orders;
create policy "orders staff read" on public.orders for select
  using (public.staff_role() is not null);
create policy "orders staff update" on public.orders for update
  using (public.staff_role() is not null) with check (public.staff_role() is not null);

-- staff profiles: you can read your own; admins can read and edit everyone
-- (accounts are created/deleted by the staff-admin Edge Function)
drop policy if exists "staff read"   on public.staff_profiles;
drop policy if exists "staff update" on public.staff_profiles;
create policy "staff read" on public.staff_profiles for select
  using (user_id = auth.uid() or public.staff_role() = 'admin');
create policy "staff update" on public.staff_profiles for update
  using (public.staff_role() = 'admin') with check (public.staff_role() = 'admin');

