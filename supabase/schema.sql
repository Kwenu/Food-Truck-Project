create table if not exists public.menu_items (
  id           text primary key,
  category_id  text not null,
  name         text not null,
  description  text not null default '',
  price        numeric(10,2) not null check (price >= 0),
  image        text not null default '',
  veg          boolean not null default true,
  tags         jsonb   not null default '[]'::jsonb,
  enabled      boolean not null default true,
  sold_out     boolean not null default false,
  prep_minutes int     not null default 10 check (prep_minutes >= 0),
  add_ons      jsonb   not null default '[]'::jsonb,
  position     bigint generated by default as identity
);
create index if not exists menu_items_category_idx on public.menu_items (category_id);

create table if not exists public.promotions (
  id            text primary key,
  code          text not null,
  title         text not null default '',
  description   text not null default '',
  type          text not null check (type in ('percent', 'flat')),
  value         numeric(10,2) not null check (value >= 0),
  min_subtotal  numeric(10,2) not null default 0 check (min_subtotal >= 0),
  active        boolean not null default true
);
create unique index if not exists promotions_code_idx on public.promotions (upper(code));

create table if not exists public.dining_tables (
  id      text primary key,
  number  int  not null unique check (number > 0),
  seats   int  not null default 4 check (seats > 0),
  code    text not null unique,
  status  text not null default 'available' check (status in ('available', 'occupied'))
);

create sequence if not exists public.order_number_seq start 1001;

create table if not exists public.orders (
  id                 uuid primary key default gen_random_uuid(),
  number             text not null unique,
  type               text not null check (type in ('takeaway', 'dine-in')),
  table_number       int,
  customer_name      text not null default '',
  customer_phone     text not null default '',
  pickup_mode        text check (pickup_mode in ('asap', 'scheduled')),
  pickup_at          timestamptz,
  lines              jsonb not null,
  note               text not null default '',
  promo_code         text,
  totals             jsonb not null,
  payment_method     text not null check (payment_method in ('cash', 'card', 'online')),
  payment_status     text not null default 'pending' check (payment_status in ('pending', 'paid', 'failed', 'refunded')),
  payment_reference  text,
  status             text not null default 'received'
                     check (status in ('received', 'confirmed', 'preparing', 'ready', 'completed', 'rejected')),
  history            jsonb not null default '[]'::jsonb,
  prep_minutes       int  not null default 12,
  estimated_ready_at timestamptz not null default now(),
  reject_reason      text,
  created_at         timestamptz not null default now()
);
create index if not exists orders_status_idx  on public.orders (status);
create index if not exists orders_created_idx on public.orders (created_at desc);

-- Staff accounts. Each row links to a Supabase Auth user (email + password).
create table if not exists public.staff_profiles (
  user_id     uuid primary key references auth.users (id) on delete cascade,
  email       text not null,
  name        text not null,
  role        text not null check (role in ('admin', 'manager', 'kitchen')),
  active      boolean not null default true,
  created_at  timestamptz not null default now()
);

