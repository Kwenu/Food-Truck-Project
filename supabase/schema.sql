-- Places an order. Prices, totals, prep time and the order number are all
-- calculated HERE from the database — the browser only says what was ordered.
create or replace function public.place_order(payload jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  s              jsonb;
  v_type         text := payload ->> 'type';
  v_table_number int;
  v_name         text := left(btrim(coalesce(payload #>> '{customer,name}', '')), 60);
  v_phone        text := left(regexp_replace(coalesce(payload #>> '{customer,phone}', ''), '\D', '', 'g'), 15);
  v_note         text := left(btrim(coalesce(payload ->> 'note', '')), 300);
  v_code         text := nullif(btrim(coalesce(payload ->> 'promoCode', '')), '');
  v_method       text := coalesce(payload #>> '{payment,method}', 'cash');
  v_pay_status   text;
  v_reference    text := nullif(left(coalesce(payload #>> '{payment,reference}', ''), 80), '');
  v_pickup_mode  text;
  v_pickup_at    timestamptz;
  v_lines        jsonb := '[]'::jsonb;
  v_subtotal     numeric := 0;
  v_max_prep     int := 0;
  v_discount     numeric := 0;
  v_taxable      numeric;
  v_tax          numeric;
  v_charges      numeric;
  v_charges_lbl  text;
  v_total        numeric;
  v_queue        int;
  v_prep         int;
  v_ready        timestamptz;
  v_tax_rate     numeric;
  v_packaging    numeric;
  v_service      numeric;
  v_base_prep    int;
  l              jsonb;
  item           public.menu_items%rowtype;
  promo          public.promotions%rowtype;
  qty            int;
  unit           numeric;
  lbl            text;
  addon          jsonb;
  labels         jsonb;
  new_order      public.orders;
begin
  select data into s from public.settings where id = 1;
  if s is null then
    raise exception 'The store is not set up yet.';
  end if;
  if not coalesce((s ->> 'isOpen')::boolean, true) then
    raise exception 'The truck is not taking orders right now.';
  end if;

  v_tax_rate  := coalesce((s ->> 'taxRate')::numeric, 0);
  v_packaging := coalesce((s ->> 'packagingFee')::numeric, 0);
  v_service   := coalesce((s ->> 'serviceChargeRate')::numeric, 0);
  v_base_prep := coalesce((s ->> 'basePrepMinutes')::numeric, 12)::int;

  if coalesce(v_type, '') not in ('takeaway', 'dine-in') then
    raise exception 'Invalid order type.';
  end if;

  if v_type = 'dine-in' then
    v_table_number := (payload ->> 'tableNumber')::int;
    perform 1 from public.dining_tables where number = v_table_number;
    if not found then
      raise exception 'That table does not exist. Please check the number on your table.';
    end if;
  else
    if char_length(v_name) < 2 then
      raise exception 'Please enter your name.';
    end if;
    if char_length(v_phone) < 7 then
      raise exception 'Please enter a valid mobile number.';
    end if;
  end if;

  if jsonb_typeof(payload -> 'lines') is distinct from 'array'
     or jsonb_array_length(payload -> 'lines') = 0
     or jsonb_array_length(payload -> 'lines') > 40 then
    raise exception 'Your cart is empty.';
  end if;

  -- Re-price every line from the live menu
  for l in select * from jsonb_array_elements(payload -> 'lines') loop
    select * into item from public.menu_items where id = l ->> 'itemId';
    if not found then
      raise exception 'An item in your cart is no longer on the menu.';
    end if;
    if not item.enabled or item.sold_out then
      raise exception '% is no longer available.', item.name;
    end if;

    qty := coalesce((l ->> 'quantity')::int, 0);
    if qty < 1 or qty > 50 then
      raise exception 'Invalid quantity for %.', item.name;
    end if;

    unit := item.price;
    labels := case when jsonb_typeof(l -> 'addOns') = 'array' then l -> 'addOns' else '[]'::jsonb end;
    for lbl in select jsonb_array_elements_text(labels) loop
      select a into addon from jsonb_array_elements(item.add_ons) a where a ->> 'label' = lbl limit 1;
      if addon is null then
        raise exception 'An add-on for % is no longer available.', item.name;
      end if;
      unit := unit + coalesce((addon ->> 'price')::numeric, 0);
    end loop;

    v_subtotal := v_subtotal + unit * qty;
    v_max_prep := greatest(v_max_prep, item.prep_minutes);
    v_lines := v_lines || jsonb_build_array(jsonb_build_object(
      'lineId',    coalesce(nullif(left(l ->> 'lineId', 40), ''), gen_random_uuid()::text),
      'itemId',    item.id,
      'name',      item.name,
      'image',     item.image,
      'veg',       item.veg,
      'unitPrice', unit,
      'quantity',  qty,
      'addOns',    labels,
      'note',      left(btrim(coalesce(l ->> 'note', '')), 200)
    ));
  end loop;

  v_subtotal := round(v_subtotal, 2);

  -- Promo code (ignored if it is invalid, inactive, or the minimum isn't met)
  if v_code is not null then
    select * into promo from public.promotions where upper(code) = upper(v_code) and active limit 1;
    if found and v_subtotal > 0 and v_subtotal >= promo.min_subtotal then
      v_code := promo.code;
      v_discount := case
        when promo.type = 'percent' then round(v_subtotal * promo.value / 100, 2)
        else least(promo.value, v_subtotal)
      end;
    else
      v_code := null;
    end if;
  end if;

  v_taxable := greatest(0, v_subtotal - v_discount);
  v_tax := round(v_taxable * v_tax_rate / 100, 2);
  if v_type = 'takeaway' then
    v_charges := v_packaging;
    v_charges_lbl := 'Packaging';
  else
    v_charges := round(v_taxable * v_service / 100, 2);
    v_charges_lbl := 'Service charge (' || coalesce(s ->> 'serviceChargeRate', '0') || '%)';
  end if;
  v_total := round(v_taxable + v_tax + v_charges, 2);

  -- Pickup time (takeaway only)
  if v_type = 'takeaway' then
    v_pickup_mode := 'asap';
    if coalesce((s ->> 'scheduledPickup')::boolean, true) and payload #>> '{pickup,mode}' = 'scheduled' then
      v_pickup_at := (payload #>> '{pickup,at}')::timestamptz;
      if v_pickup_at is null
         or v_pickup_at < now() - interval '5 minutes'
         or v_pickup_at > now() + interval '24 hours' then
        raise exception 'Please pick a valid pickup time.';
      end if;
      v_pickup_mode := 'scheduled';
    end if;
  end if;

  select count(*)::int into v_queue from public.orders where status in ('received', 'confirmed', 'preparing');
  v_prep  := least(60, greatest(v_base_prep, v_max_prep) + v_queue * 2);
  v_ready := coalesce(v_pickup_at, now() + make_interval(mins => v_prep));

  -- Customers pay at the cashier (cash or card machine), so every new order starts UNPAID.
  -- Only staff can mark it paid, which means a customer can never fake a payment.
  if v_method not in ('cash', 'card') then
    raise exception 'Please choose cash or card (paid at the cashier).';
  end if;
  v_pay_status := 'pending';
  v_reference := null;

  insert into public.orders (
    number, type, table_number, customer_name, customer_phone,
    pickup_mode, pickup_at, lines, note, promo_code, totals,
    payment_method, payment_status, payment_reference,
    status, history, prep_minutes, estimated_ready_at
  ) values (
    'EW-' || nextval('public.order_number_seq')::text, v_type, v_table_number, v_name, v_phone,
    v_pickup_mode, v_pickup_at, v_lines, v_note, v_code,
    jsonb_build_object(
      'subtotal', v_subtotal, 'discount', v_discount, 'tax', v_tax,
      'charges', v_charges, 'chargesLabel', v_charges_lbl, 'total', v_total
    ),
    v_method, v_pay_status, v_reference,
    'received', jsonb_build_array(jsonb_build_object('status', 'received', 'at', now())),
    v_prep, v_ready
  ) returning * into new_order;

  if v_type = 'dine-in' then
    update public.dining_tables set status = 'occupied' where number = v_table_number;
  end if;

  return public.order_public_json(new_order);
end;
$$;

-- Look up orders by number (customer order tracking). Phone numbers are never returned.
create or replace function public.get_orders(order_numbers text[])
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(jsonb_agg(public.order_public_json(o) order by o.created_at desc), '[]'::jsonb)
  from public.orders o
  where o.number in (select upper(btrim(n)) from unnest(order_numbers[1:10]) as n)
$$;

-- How many orders are in the kitchen right now (used for the wait-time estimate).
create or replace function public.queue_count()
returns int
language sql
stable
security definer
set search_path = public
as $$
  select count(*)::int from public.orders where status in ('received', 'confirmed', 'preparing')
$$;

-- Open / close the truck (admin or manager).
create or replace function public.set_truck_open(is_open boolean)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if coalesce(public.staff_role(), '') not in ('admin', 'manager') then
    raise exception 'Not allowed.';
  end if;
  update public.settings
     set data = jsonb_set(data, '{isOpen}', to_jsonb(is_open)), updated_at = now()
   where id = 1;
end;
$$;

