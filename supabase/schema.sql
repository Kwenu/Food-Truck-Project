-- settings: everyone reads, admin edits
drop policy if exists "settings read"  on public.settings;
drop policy if exists "settings write" on public.settings;
create policy "settings read"  on public.settings for select using (true);
create policy "settings write" on public.settings for update
  using (public.staff_role() = 'admin') with check (public.staff_role() = 'admin');

-- menu data: everyone reads, admin/manager edit
do $$
declare t text;
begin
  foreach t in array array['categories', 'menu_items', 'dining_tables'] loop
    execute format('drop policy if exists "%1$s read" on public.%1$I', t);
    execute format('drop policy if exists "%1$s insert" on public.%1$I', t);
    execute format('drop policy if exists "%1$s update" on public.%1$I', t);
    execute format('drop policy if exists "%1$s delete" on public.%1$I', t);
    execute format('create policy "%1$s read" on public.%1$I for select using (true)', t);
    execute format($p$create policy "%1$s insert" on public.%1$I for insert
                      with check (coalesce(public.staff_role(), '') in ('admin', 'manager'))$p$, t);
    execute format($p$create policy "%1$s update" on public.%1$I for update
                      using (coalesce(public.staff_role(), '') in ('admin', 'manager'))
                      with check (coalesce(public.staff_role(), '') in ('admin', 'manager'))$p$, t);
    execute format($p$create policy "%1$s delete" on public.%1$I for delete
                      using (coalesce(public.staff_role(), '') in ('admin', 'manager'))$p$, t);
  end loop;
end $$;

-- promotions: customers only see active ones; admin/manager manage all
